type LegalPageKind = "privacy" | "terms" | "delete-account";

/** Legal text comes from the legacy dictionary; "{app}" stands for the product name (ADR-0005). */
const lt = (text: string) => t(text).replaceAll("{app}", brand.name);

/** The operator's support mailbox from the build environment; a visible placeholder until it is configured. */
function SupportEmail({ subject = false }: { subject?: boolean }) {
  if (!supportEmail) return <strong>{lt("адрес поддержки (ещё не настроен)")}</strong>;
  const topic = `${brand.name}: ${getLanguage() === "en" ? "account deletion" : "удаление аккаунта"}`;
  return <a href={`mailto:${supportEmail}${subject ? `?subject=${encodeURIComponent(topic)}` : ""}`}>{supportEmail}</a>;
}

